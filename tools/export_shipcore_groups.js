// Builds studio/data/shipcore_groups.js from GVK_ShipCoreFramework's ShipCoreConfig_Groups.xml: the UP cost
// of each weapon block ("UP Weapons" CountWeight) and which blocks are Relic weapons ("H Relic Weapons").
// Keys are exact "TypeId/SubtypeId" (ShipCore matches both exactly; an empty SubtypeId matches only an empty one).
// Run from the repo root:
//   node tools/export_shipcore_groups.js            (sibling checkout ../GVK_ShipCoreFramework)
//   node tools/export_shipcore_groups.js --xml <path>
//   node tools/export_shipcore_groups.js --check    (exit 1 if the committed file is stale; skips if no XML)
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'studio', 'data', 'shipcore_groups.js');
const XML_REL = 'Content/Data/ShipCoreConfig_Groups.xml';
const UP_GROUP = 'UP Weapons';
const RELIC_GROUP = 'H Relic Weapons';

function argValue(name) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

/// <summary>Groups from the XML: { [name]: [{ typeId, subtypeId, countWeight }] }, TypeId without MyObjectBuilder_.</summary>
function parseShipCoreGroups(xmlText) {
  const groups = {};
  const text = String(xmlText).replace(/<!--[\s\S]*?-->/g, '');
  const tag = (s, name) => {
    const m = s.match(new RegExp(`<${name}\\s*/>|<${name}>([\\s\\S]*?)</${name}>`));
    return m ? (m[1] || '').trim() : null;
  };
  for (const g of text.match(/<BlockGroup>[\s\S]*?<\/BlockGroup>/g) || []) {
    const name = tag(g, 'Name');
    if (!name) continue;
    groups[name] = (g.match(/<BlockTypes>[\s\S]*?<\/BlockTypes>/g) || []).map((b) => ({
      typeId: (tag(b, 'TypeId') || '').replace(/^MyObjectBuilder_/i, ''),
      subtypeId: tag(b, 'SubtypeId') || '',
      countWeight: parseFloat(tag(b, 'CountWeight')) || 0
    }));
  }
  return groups;
}

function buildData(groups) {
  const upWeapons = {};
  for (const b of groups[UP_GROUP] || []) upWeapons[`${b.typeId}/${b.subtypeId}`] = b.countWeight;
  const relicWeapons = (groups[RELIC_GROUP] || []).map((b) => `${b.typeId}/${b.subtypeId}`);
  return { upWeapons, relicWeapons };
}

function render(data, commit) {
  const lines = [
    '// Generated by tools/export_shipcore_groups.js from GVK_ShipCoreFramework ' + XML_REL + '. Do not edit by hand.',
    '// upWeapons: UPs per weapon block ("UP Weapons" CountWeight); relicWeapons: blocks in "H Relic Weapons".',
    '// Keys are exact "TypeId/SubtypeId", as ShipCore matches them.',
    'const SHIPCORE_GROUPS = ' + JSON.stringify({
      source: { repo: 'GV-Server-Mods/GVK-ShipCoreFramework', file: XML_REL, commit },
      upWeapons: data.upWeapons,
      relicWeapons: data.relicWeapons
    }, null, 2) + ';',
    "if (typeof module !== 'undefined' && module.exports) module.exports = SHIPCORE_GROUPS;",
    ''
  ];
  return lines.join('\r\n');
}

function main() {
  const xmlPath = argValue('--xml') || process.env.GVK_SHIPCORE_XML
    || path.join(ROOT, '..', 'GVK_ShipCoreFramework', ...XML_REL.split('/'));
  const check = process.argv.includes('--check');
  if (!fs.existsSync(xmlPath)) {
    if (check) { console.log('  PASS  (skipped: ShipCore XML not found at ' + xmlPath + ')'); return; }
    console.error('ShipCore XML not found: ' + xmlPath);
    process.exit(1);
  }
  const data = buildData(parseShipCoreGroups(fs.readFileSync(xmlPath, 'utf8')));
  if (check) {
    const committed = require(OUT);
    const same = JSON.stringify(committed.upWeapons) === JSON.stringify(data.upWeapons)
      && JSON.stringify(committed.relicWeapons) === JSON.stringify(data.relicWeapons);
    console.log(`  ${same ? 'PASS' : 'FAIL'}  studio/data/shipcore_groups.js matches ${XML_REL}`);
    if (!same) { console.error('  FAIL  stale: run node tools/export_shipcore_groups.js and commit'); process.exit(1); }
    return;
  }
  let commit = '';
  try {
    commit = execFileSync('git', ['-C', path.dirname(xmlPath), 'log', '-1', '--format=%H', '--', path.basename(xmlPath)], { encoding: 'utf8' }).trim();
  } catch (e) {
    console.warn('No git commit for the XML (' + e.message.split('\n')[0] + ')');
  }
  fs.writeFileSync(OUT, render(data, commit), 'utf8');
  console.log(`Wrote studio/data/shipcore_groups.js: ${Object.keys(data.upWeapons).length} UP weapons, ${data.relicWeapons.length} relic entries`);
}

module.exports = { parseShipCoreGroups, buildData };
if (require.main === module) main();
